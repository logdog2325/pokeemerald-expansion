def spot(o):
    return "(%d, %d)" % (o["x"], o["y"])


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--missing", action="store_true", help="list the NPCs without a uniform branch")
    ap.add_argument("--skipped", action="store_true", help="what isn't counted, by reason")
    ap.add_argument("--map", help="every object on the maps whose name contains this")
    ap.add_argument("--maps", action="store_true", help="the maps that can / can't be entered in uniform")
    ap.add_argument("--doc", action="store_true", help="rewrite the generated part of docs/reputation_dialogue.md")
    ap.add_argument("-v", "--verbose", action="store_true")
    args = ap.parse_args()
    t0 = time.time()
    cov = Coverage(args.verbose)
    world = cov.chk.world
    if args.maps:
        print("enterable in uniform (%d): %s" % (len(cov.period.maps), " ".join(sorted(world.pretty(m) for m in cov.period.maps))))
        rest = sorted(md.name for md in world.maps.values() if md.id not in cov.period.maps)
        print("\nnot enterable in uniform (%d): %s" % (len(rest), " ".join(rest)))
        return 0
    if args.doc:
        write_doc(cov)
        return 0
    if args.map:
        for name, o, verdict, why in cov.rows:
            if args.map.lower() in name.lower():
                print("%-36s %-3s %-9s %-26s %-60s %s" % (name, o["index"], spot(o), o["graphics_id"][14:], o.get("script"),
                                                       {"yes": "REACTS", "no": "MISSING"}.get(verdict, "skip: " + why)))
        return 0
    if args.skipped:
        by = {}
        for name, o, verdict, why in cov.rows:
            if verdict == "skip" and why != "no script":
                by.setdefault(re.sub(r" \(hide flag .*\)", "", why), []).append((name, o))
        for why, items in sorted(by.items(), key=lambda kv: -len(kv[1])):
            print("%5d  %s" % (len(items), why))
            if args.verbose:
                for name, o in items:
                    print("         %-36s %-9s %-24s %s" % (name, spot(o), o["graphics_id"][14:], o.get("script")))
        return 0
    per = {}
    for name, o, verdict, why in cov.counted():
        per.setdefault(name, [0, 0])
        per[name][1] += 1
        if verdict == "yes":
            per[name][0] += 1
    if args.missing:
        n = 0
        for name, o, verdict, why in cov.rows:
            if verdict == "no":
                n += 1
                line = cov.first_line(o["script"])
                print("%-36s %-9s %-22s %s\n      %s" % (name, spot(o), o["graphics_id"][14:], o["script"],
                                                       line[:150] + ("…" if len(line) > 150 else "")))
        print("%d NPC(s) without a uniform branch" % n)
        return 1 if n else 0
    for name in sorted(per):
        y, t = per[name]
        print("%-40s %3d / %-3d %s" % (name, y, t, "" if y == t else "(%d missing)" % (t - y)))
    yes = sum(v[0] for v in per.values())
    tot = sum(v[1] for v in per.values())
    print("\n%d of %d people the player can meet in uniform react to it (%.0f%%), %d missing; %d maps enterable in "
          "uniform (%d legs of the story), %.0fs" % (yes, tot, 100.0 * yes / max(tot, 1), tot - yes, len(cov.period.maps),
                                                   len(cov.period.legs), time.time() - t0))
    return 1 if yes < tot else 0


if __name__ == "__main__":
    sys.exit(main())
