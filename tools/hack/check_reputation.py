AREA_TITLES = {}  # file stem -> section title (default: from the file's first comment line)
# the generated sections in story order (files not listed follow, by name)
AREA_ORDER = ["draconid_village", "littleroot", "oldale", "petalburg", "routes_south", "rustboro", "dewford", "sea",
              "slateport", "mauville", "routes_central", "verdanturf", "fallarbor", "lavaridge", "routes_north",
              "fortree", "lilycove", "lilycove_contest", "mossdeep", "sootopolis", "pacifidlog", "ever_grande"]


def doc_sections(already):
    """Markdown for the reputation scripts the hand-written tables don't list"""
    out = []
    total = 0
    paths = sorted(glob.glob(os.path.join(REP_DIR, "*.pory")))
    rank = {stem: i for i, stem in enumerate(AREA_ORDER)}
    paths.sort(key=lambda p: (rank.get(os.path.basename(p)[:-5], len(rank)), p))
    for path in paths:
        src = open(path).read()
        title = AREA_TITLES.get(os.path.basename(path)[:-5])
        if title is None:
            m = re.match(r"//.*?–\s*(.+?)\s*(?:\(|$)", src.splitlines()[0])
            title = m.group(1).rstrip(".") if m else os.path.basename(path)
        texts = {}
        for kind, name, body in gsd.blocks(src):
            if kind == "text":
                f = gsd.FORMAT.search(body)
                texts[name] = gsd.join_strings(f.group(1)) if f else gsd.join_strings(body)
        rows = []
        for m in re.finditer(r"((?:^//[^\n]*\n)*)^script\s+(\w+)\s*\{", src, re.M):
            name = m.group(2)
            if name in already or "_DraconidRep" not in name or any(name.endswith(a) for a in already if a.startswith("_")):
                continue
            body = next(b for k, n, b in gsd.blocks(src[m.start(2) - 7:]) if n == name)
            comment = " ".join(l[2:].strip() for l in m.group(1).splitlines())
            who, vanilla = comment, ""
            vm = re.search(r'\(vanilla[^:]*:\s*(.*)\)\s*$', comment)
            if vm:
                who, vanilla = comment[:vm.start()].strip(), vm.group(1).strip()
            uni, rev = [], []
            for t in re.findall(r"msgbox\(\s*(\w+)|message\(\s*(\w+)", body):
                t = t[0] or t[1]
                if t not in texts:
                    continue
                tm = re.search(r"(Uniform|Revealed)(\w*)$", t)
                if not tm:
                    continue
                boxes = " / ".join(gsd.pretty(texts[t]))
                branch = re.sub(r"(?<=[a-z])(?=[A-Z])", " ", tm.group(2)).strip()
                cell = ("**%s:** " % branch if branch else "") + boxes
                (uni if tm.group(1) == "Uniform" else rev).append(cell)
            if "MSGBOX_DEFAULT" in body and "RepTurnAway" not in body:
                # the line is said first, then the vanilla script runs (its gift, service or story line)
                uni = [c + " → *vanilla script*" for c in uni]
                rev = [c + " → *vanilla script*" for c in rev]
            mapname = map_of(name)
            rows.append("| %s | %s | `%s` | %s | %s | %s |" % (mapname, who, name, vanilla or "–",
                                                              "<br>".join(uni) or "vanilla",
                                                              "<br>".join(rev) or "vanilla"))
        if rows:
            total += len(rows)
            out += ["### %s" % title, "",
                    "| Map | NPC | Script | Pre-uniform (vanilla) | Uniform | Revealed |", "|---|---|---|---|---|---|"]
            out += rows + [""]
    return out, total


def map_of(label):
    names = [os.path.basename(os.path.dirname(p)) for p in glob.glob(os.path.join(ROOT, "data/maps/*/map.json"))]
    best = ""
    for n in names:
        if label.startswith(n + "_") and len(n) > len(best):
            best = n
    return best or label.split("_EventScript")[0]


def write_doc(cov):
    text = open(DOC).read()
    head = text.split(DOC_BEGIN)[0]
    tail = text.split(DOC_END, 1)[1] if DOC_END in text else ""
    already = set(re.findall(r"`(\w+_DraconidRep\w+)`", head + tail))
    already |= set(re.findall(r"`…(_\w*DraconidRep\w+)`", head + tail))  # "…_DraconidRepX": the map prefix left out
    sections, total = doc_sections(already)
    counted = cov.counted()
    yes = sum(1 for r in counted if r[2] == "yes")
    body = [DOC_BEGIN, "", "## More townsfolk (round 2, D-360)", "",
            "Written by `check_reputation.py --doc` from the scripts (%d NPCs). Coverage now: **%d of %d** people the "
            "player can meet in uniform react to it (`python3 tools/hack/check_reputation.py`)." % (total, yes, len(counted)),
            ""] + sections + [DOC_END]
    open(DOC, "w").write(head + "\n".join(body) + (tail or "\n"))
    print("wrote %s: %d generated rows" % (os.path.relpath(DOC, ROOT), total))


