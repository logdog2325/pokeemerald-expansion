def talkable(o, tiles, view):
    """can the player stand next to the object (or face it across a counter) on a flooded tile?"""
    x, y = o.get("cx", o["x"]), o.get("cy", o["y"])
    rx = int(o.get("movement_range_x") or 0)
    ry = int(o.get("movement_range_y") or 0)
    for ox in range(x - rx, x + rx + 1):
        for oy in range(y - ry, y + ry + 1):
            for dx, dy in cp.DIRS.values():
                if (ox + dx, oy + dy) in tiles:
                    return True
                mx, my = ox + dx, oy + dy
                if view.inside(mx, my) and view.beh[my * view.w + mx] == cp.COUNTER and (ox + 2 * dx, oy + 2 * dy) in tiles:
                    return True
    return False


class AnyItems(cp.Layer):
    """a bag where an item no story scene gave is unknown, not missing: a gate script's checkitem goes both ways"""
    __slots__ = ()

    def get(self, k, default=None):
        v = super().get(k, None)
        return cp.UNK if v is None else v

    def copy(self):
        return AnyItems(self.base, dict(self.diff))


class Period:
    """floods every uniform leg of the story; maps entered, objects shown"""

    def __init__(self, chk, verbose=False):
        self.chk = chk
        self.verbose = verbose
        self.maps = set()        # MAP_X entered in uniform
        self.visible = {}        # MAP_X -> {object index} shown on a uniform leg
        self.shown = {}          # MAP_X -> {object index} shown and next to a reachable tile
        self.legs = []           # leg ids in uniform
        self.states = []         # the simulated state after each of those legs' scenes
        self.tiles = {}          # MAP_X -> {(x, y)} flooded on any of them
        self.fly = set()         # MAP_X whose heal spot a flood reached
        self.warp_labels = self._warp_labels()
        table = json.load(open(cp.TABLE))
        self.rep = chk.sim.vkey(REP_VAR)
        self.uniform = chk.c.value("REPUTATION_UNIFORM")
        cp.run_story(chk, table, only="-", on_leg=self.on_leg)

    def _warp_labels(self):
        """script labels from which a warp command (or a warp special) is reachable"""
        s = self.chk.scripts
        warpy = set()
        for label in s.labels:
            for op, args in walk_cmds(s, label, limit=400):
                if op in cp.WARP_OPS or (op == "special" and args and args[0] in cp.SPECIAL_WARPS):
                    warpy.add(label)
                    break
        return warpy

    def on_leg(self, leg, st, pos):
        if st.var(self.rep) != self.uniform:
            return
        t0 = time.time()
        self.legs.append(leg.get("id"))
        st = st.flattened()
        self.states.append(st)
        srch = cp.Search(self.chk, st, set(self.fly))
        prev = {}
        frontier = []
        start = srch.node_at(*pos)
        if start is not None:
            frontier.append(start)
        frontier += srch.fly_nodes()
        tried = set()
        while frontier:
            self._flood(srch, frontier, prev)
            frontier = []
            for m in sorted({n[0] for n in prev}):
                for dest in self._script_warps(srch, m, tried):
                    n = srch.node_at(*dest)
                    if n is not None and n not in prev:
                        frontier.append(n)
        maps = {n[0] for n in prev}
        tiles = {n[:3] for n in prev}
        for h in self.chk.world.heal:
            if "respawn_map" in h and (h["map"], h["x"], h["y"]) in tiles:
                self.fly.add(h["map"])
        by_map = {}
        for n in prev:
            by_map.setdefault(n[0], set()).add((n[1], n[2]))
        for m in maps:
            self.tiles.setdefault(m, set()).update(by_map[m])
            v = srch.view(m)
            if v is not None:
                self.visible.setdefault(m, set()).update(o["index"] for o in v.objects)
                self.shown.setdefault(m, set()).update(o["index"] for o in v.objects if talkable(o, by_map[m], v))
        new = maps - self.maps
        self.maps |= maps
        if self.verbose:
            print("leg %-6s %-40s %4d maps (+%d) %.1fs" % (leg.get("id"), self.chk.world.pretty(pos[0]), len(maps),
                                                           len(new), time.time() - t0), file=sys.stderr)

    def _flood(self, srch, starts, prev):
        dq = []
        for s in starts:
            if s not in prev:
                prev[s] = None
                dq.append(s)
        i = 0
        while i < len(dq):
            n = dq[i]
            i += 1
            for nn, obs, how in srch.neighbors(n, set()):
                if obs or nn in prev:
                    continue
                prev[nn] = n
                dq.append(nn)

    def _script_warps(self, srch, map_id, tried):
        """where the warping scripts of a flooded map's objects, signs and coord triggers send the player"""
        v = srch.view(map_id)
        if v is None:
            return []
        runs = []
        for o in v.objects:
            if o.get("script") in self.warp_labels:
                runs.append((o["script"], o["index"]))
        for ev in v.md.bgs:
            if ev.get("script") in self.warp_labels:
                runs.append((ev["script"], 0))
        for evs in v.triggers.values():
            for ev in evs:
                if ev.get("script") in self.warp_labels:
                    runs.append((ev["script"], 0))
        out = []
        for label, idx in runs:
            key = (map_id, label)
            if key in tried:
                continue
            tried.add(key)
            ctx = cp.Ctx(map_id, last_talked=idx, budget=cp.SIDE_BUDGET)
            st = v.state.copy()
            st.items = AnyItems(st.items.base, dict(st.items.diff))  # side gifts (the Pokéblock Case) may be in the bag
            self.chk.sim.run(label, st, ctx)
            for w in ctx.warps:
                p = self.chk.warp_position(w)
                if p and p[0] in self.chk.world.maps:
                    out.append(p)
                    dv = srch.view(p[0])
                    if dv is not None and dv.inside(p[1], p[2]) and dv.tile(p[1], p[2])[0] in cp.STEP_WARP:
                        out.append((p[0], p[1], p[2] + 1))  # arriving on a door: the player steps out of it
        return out


