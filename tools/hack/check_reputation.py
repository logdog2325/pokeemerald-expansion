def walk_cmds(scripts, label, limit=4000):
    """(op, args) of every command reachable from label: goto/call, the conditional jumps, switch cases"""
    if label not in scripts.labels:
        return
    seen = set()
    todo = [scripts.labels[label]]
    n = len(scripts.cmds)
    count = 0
    while todo and count < limit:
        pc = todo.pop()
        while pc < n and pc not in seen and count < limit:
            seen.add(pc)
            count += 1
            op, args, _, _ = scripts.cmds[pc]
            yield op, args
            if op in ("goto", "call") or op.startswith(("goto_if", "call_if")) or op == "case":
                target = args[-1] if args else None
                if target in scripts.labels:
                    todo.append(scripts.labels[target])
                if op == "goto":
                    break
            if op in ("end", "return", "step_end", "releaseall_end"):
                break
            pc += 1


def straight_cmds(scripts, label, limit=60):
    """the commands run before the first branch (following plain gotos)"""
    out = []
    pc = scripts.labels.get(label)
    seen = set()
    while pc is not None and pc < len(scripts.cmds) and len(out) < limit and pc not in seen:
        seen.add(pc)
        op, args, _, _ = scripts.cmds[pc]
        out.append((op, args))
        if op == "goto":
            pc = scripts.labels.get(args[0]) if args else None
            continue
        if op in ("end", "return") or op.startswith(("goto_if", "call_if")) or op in ("switch", "case"):
            break
        pc += 1
    return out


def reacts(scripts, label):
    """True if code reachable from label branches on the uniform"""
    if label in UNIFORM_ONLY:
        return True
    switch_var = None
    for op, args in walk_cmds(scripts, label):
        if op == "switch":
            switch_var = args[0] if args else None
            continue
        if op == "case" and switch_var == REP_VAR and args and args[0] in REP_VALUES:
            return True
        if REP_VAR in args and REP_VALUES & set(args):
            return True
        if OUTFIT_VAR in args and "PLAYER_OUTFIT_MAGMA" in args:
            return True
    return False


def category(scripts, o):
    """None for a person to count, else why the object isn't counted"""
    s = o.get("script") or "0x0"
    g = o.get("graphics_id", "")
    if s in ("0x0", "NULL", ""):
        return "no script"
    if s in SKIP:
        return SKIP[s]
    if o.get("trainer_type") not in (None, "TRAINER_TYPE_NONE", "0"):
        return "trainer"
    if s in ITEM_SCRIPTS or g == "OBJ_EVENT_GFX_ITEM_BALL":
        return "item ball"
    if s in BERRY_SCRIPTS or "BERRY_TREE" in g:
        return "berry tree"
    if s in FIELD_SCRIPTS or g in cp.BOULDER + cp.ROCK + cp.TREE:
        return "Cut tree / Rock Smash rock / Strength boulder"
    if POKEMON_GFX.match(g):
        return "a Pokémon (it only cries)"
    if THING_GFX.match(g):
        return "a thing, not a person"
    if any(TRAINER_OPS.match(op) for op, _ in straight_cmds(scripts, s)):
        return "trainer"
    return None


class Coverage:
    def __init__(self, verbose=False):
        self.chk = cp.Checker()
        self.texts = text_index()
        self.period = Period(self.chk, verbose)
        self.rows = []  # (map name, object, verdict, reason)
        world = self.chk.world
        self.optional_talks()
        for md in sorted(world.maps.values(), key=lambda m: m.name):
            entered = md.id in self.period.maps
            shown = self.period.shown.get(md.id, set())
            for o in md.objects:
                why = category(self.chk.scripts, o)
                if why is None and not entered:
                    why = "not enterable in uniform"
                elif why is None and o["index"] not in shown:
                    if o["index"] not in self.period.visible.get(md.id, set()):
                        why = "hidden for the whole uniform period (hide flag %s)" % o.get("flag")
                    else:
                        why = "out of reach in uniform (no tile next to it can be reached)"
                if why is not None:
                    self.rows.append((md.name, o, "skip", why))
                elif reacts(self.chk.scripts, o["script"]):
                    self.rows.append((md.name, o, "yes", ""))
                else:
                    self.rows.append((md.name, o, "no", ""))

    def optional_talks(self):
        """people a side talk brings out (LANETTE after the FALLARBOR chat, the WHITE HERB florist after the flower
        shop): the flags the scripts of the people met in uniform write are unknown, not the story's value"""
        chk, per = self.chk, self.period
        story = set()  # flags the story's scenes write: the simulation already follows them
        for leg in json.load(open(cp.TABLE))["legs"]:
            for label in cp.scene_labels(leg):
                for op, args in walk_cmds(chk.scripts, label, limit=4000):
                    if op in ("setflag", "clearflag") and args:
                        story.add(chk.sim.fkey(args[0]))
        optional = set()
        for m in per.maps:
            md = chk.world.maps[m]
            for o in md.objects:
                if o["index"] in per.shown.get(m, ()) and category(chk.scripts, o) is None:
                    for op, args in walk_cmds(chk.scripts, o["script"], limit=600):
                        if op in ("setflag", "clearflag") and args and chk.sim.fkey(args[0]) not in story:
                            optional.add(chk.sim.fkey(args[0]))
        for m in per.maps:
            md = chk.world.maps[m]
            hidden = [o for o in md.objects if o["index"] not in per.visible.get(m, ())
                      and category(chk.scripts, o) is None]
            if not hidden:
                continue
            for st in per.states:
                st2 = st.copy()
                for k in optional:
                    st2.flags[k] = cp.UNK
                v = cp.MapView(chk, md, st2)
                for o in v.objects:
                    if any(o["index"] == h["index"] for h in hidden):
                        per.visible.setdefault(m, set()).add(o["index"])
                        if talkable(o, per.tiles.get(m, set()), v):
                            per.shown.setdefault(m, set()).add(o["index"])

    def counted(self):
        return [r for r in self.rows if r[2] != "skip"]

    def first_line(self, label):
        """the first text the script shows (for --missing)"""
        for op, args in walk_cmds(self.chk.scripts, label, limit=200):
            if op in ("msgbox", "message") and args and args[0] in self.texts:
                return self.texts[args[0]]
        return ""


def text_index():
    out = {}
    files = glob.glob(os.path.join(ROOT, "data/maps/*/scripts.inc")) + glob.glob(
        os.path.join(ROOT, "data/scripts/**/*.inc"), recursive=True) + glob.glob(os.path.join(ROOT, "data/text/*.inc"))
    lab = re.compile(r'^(\w+)::?[^\n]*\n((?:[ \t]*\.string "(?:[^"\\]|\\.)*"[^\n]*\n)+)', re.M)
    for path in files:
        for name, body in lab.findall(open(path, errors="replace").read()):
            out[name] = " / ".join(gsd.pretty("".join(re.findall(r'\.string "((?:[^"\\]|\\.)*)"', body))))
    return out


